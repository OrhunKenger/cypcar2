        'https://picsum.photos/seed/${id}b/600/900',
        'https://picsum.photos/seed/${id}c/600/900',
      ],
      viewCount: viewCount,
      isFavorite: isFavorite,
      isPinned: pinSlot != null,
      pinSlot: pinSlot,
      location: location,
      fuelType: fuelType,
      transmission: transmission,
      mileage: mileage,
      postedAt: DateTime.now().subtract(Duration(hours: num * 3)),
